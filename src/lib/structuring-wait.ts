/**
 * 整理（/api/structure）の待ち時間中に出す文言。
 *
 * 実データで75秒かかることを確認済み（2026-09-14の調査。docs/reports参照）。
 * その間ずっと同じ「整理しています…」のままだと、進んでいるのか止まって
 * いるのか本人には分からず、閉じてやり直したくなる。閉じると signal 経由で
 * 生成そのものが中断され、対話をもう一度整理し直すことになるので、
 * 経過時間に応じて文言を変え、閉じないよう促す。
 */
export function structuringMessage(elapsedMs: number): string {
  if (elapsedMs < 12_000) return "あなたの言葉を整理しています…";
  if (elapsedMs < 35_000) return "実行できる形に、じっくり落とし込んでいます…";
  if (elapsedMs < 60_000) return "もう少しで終わります。閉じずにお待ちください…";
  return "時間がかかっていますが、続けています。閉じると最初からやり直しになるので、もう少しだけお待ちください…";
}
