import type { AnyPhaseId } from "@/types/goal";

/**
 * 対話中に開ける「コツ」。
 *
 * ねらいは、AIが答えを出して終わりにしないこと。
 * とくに If-Then プランニングは、作り方そのものを持ち帰ってもらいたい。
 * だからコーチが代わりに作るのではなく、書き方を見せて本人に書かせる。
 */
export interface Tip {
  id: string;
  /** チップに出す短い文字 */
  label: string;
  title: string;
  /** 本文。段落ごとに分ける */
  body: string[];
  /** 手順があるとき */
  steps?: string[];
  /** 良い例と悪い例。悪い例には「なぜ悪いか」を必ず添える */
  examples?: { good: string; bad: string; whyBad: string }[];
}

const IF_THEN: Tip = {
  id: "if-then-howto",
  label: "If-Thenの作り方",
  title: "「もし◯◯になったら、△△する」の作り方",
  body: [
    "つまずきを乗り越える計画は、その場の意志ではなく、事前の一文で決まります。コツは、きっかけと行動をどちらも「他人が見ても分かる」ところまで具体的にすることです。",
  ],
  steps: [
    "つまずきを『場面』まで具体化する。いつ・どこで・何があったときかを入れる",
    "その場面を「もし〜になったら」の形に置き換える",
    "対策を「〜する」の形で1つだけ決める。5分でできる大きさまで小さくする",
  ],
  examples: [
    {
      good: "もし 残業して22時に帰宅したら → 風呂に入る前に、5分だけ求人サイトを開く",
      bad: "もし やる気が出なかったら → 気合を入れ直して頑張る",
      whyBad:
        "「やる気が出ない」は場面ではなく気分なので、来たことに自分で気づけません。「頑張る」も行動ではないので、その瞬間に何をすればいいか分かりません。",
    },
    {
      good: "もし 日曜の夜に翌週の予定を立てるとき → カレンダーに練習の枠を先に入れる",
      bad: "もし 時間ができたら → 練習する",
      whyBad:
        "「時間ができたら」は、いつ来るか分からない条件です。きっかけは自分でほぼ確実に訪れると分かっているものを選びます。",
    },
  ],
};

const OBSTACLE: Tip = {
  id: "obstacle-howto",
  label: "つまずきの見つけ方",
  title: "つまずきそうなことの見つけ方",
  body: [
    "「時間がない」「忙しい」は、ほとんどの場合その先に本当の理由があります。もう一段だけ掘ってみてください。",
    "思いつかないときは、前に似たことをやめたときのことを思い出すのが早道です。",
  ],
  steps: [
    "過去に同じようなことが続かなかったときを思い出す",
    "そのとき、具体的に何が起きていたかを言葉にする",
    "それがまた起きるとしたら、いつ起きそうかを決める",
  ],
};

